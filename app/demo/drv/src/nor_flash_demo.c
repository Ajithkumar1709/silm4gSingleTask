unsigned int checksum(unsigned char * src, unsigned int len, unsigned int checksum)
{
	unsigned int * start = (unsigned int *)src;
	unsigned int * end = start + (len / sizeof(unsigned int));
	while (start < end) {
		checksum ^= (*start++);
	}
	return checksum;
}

unsigned char *generate_test_4K_data(unsigned int offset)
{
	unsigned char *original_test_data = test_4k;
	unsigned int temp_offset = offset*256;

	for(unsigned int i = 0;i<256;i++)
	{
		original_test_data[temp_offset+i] = 0x00;	
	}

	return original_test_data;
}

int nor_flash_demo(void)
{
	int ret = 0;
	unsigned int count = 0;
	unsigned int corrupt_count = 0;
	unsigned int block_count = 0;
	unsigned int *checksum_list = NULL;
	unsigned int addr = 0;

	block_count = TARGET_FLASH_SIZE / SIZE_4K;
	addr = TARGET_FLASH_ADDR;
	checksum_list = (unsigned int *)ol_malloc(block_count*sizeof(int));
	
	while(count == 0){
		op_uart_printf("nor_flash_demo : start main loop count %d  \n", count);
		for(unsigned int scan_count = 0;scan_count < block_count;scan_count++)
		{
			unsigned int current_checksum = 0;
			unsigned char read_buf[SIZE_4K] = {0};
			unsigned int scan_addr = addr + scan_count*SIZE_4K;
			unsigned char*wirte_buf = generate_test_4K_data(scan_count);

			ol_norflash_do_erase(NULL,scan_addr,SIZE_4K);
			ol_norflash_do_write(NULL,scan_addr,(unsigned int)wirte_buf,SIZE_4K);
			current_checksum = checksum(wirte_buf,SIZE_4K,0);
			checksum_list[scan_count] = current_checksum;
			
			memset(read_buf,0, SIZE_4K);
			ol_norflash_do_read(NULL, scan_addr, (unsigned int)read_buf, SIZE_4K);
			current_checksum = checksum(read_buf,SIZE_4K,0);		
			
			op_uart_printf("nor_flash_demo : scan block %d checksum: %x,record checksum: %x \n", \
				scan_count,current_checksum,checksum_list[scan_count]);
			if(checksum_list[scan_count] != current_checksum)
			{
				corrupt_count++;
				break;
			}
			ol_os_task_sleep(100);
		}
		
		if(corrupt_count > 0)
			break;
		count++;
	}

	op_uart_printf("nor_flash_demo : test end \n");

	return 0;
}


