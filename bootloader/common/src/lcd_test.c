static int __lcd_open(struct s_lcd_ctx **plcd, struct panel_spec **ppanel)
{
	struct s_lcd_ctx *lcd = NULL;
	struct panel_spec *panel = NULL;
	int ret = -1;

	LCDLOGI("Info: __lcd_open +++\r\n");

	if(g_lcd_test_status == LCD_TEST_STATUS_POWERON){
		LCDLOGE("ERR: __lcd_open: lcd has been in power on status!!\r\n");
		return -1;
	}

	lcd_env_prepare();
//#ifdef USE_MEDIACLK_INTERFACE
//	lcd_poweron();
//#else
	lcd_ass_poweron();
//#endif
	g_lcd_test_status = LCD_TEST_STATUS_POWERON;

	lcd = (struct s_lcd_ctx*)lcd_init(LCD_WORK_MODE_INTERRUPT);
	if(NULL == lcd){
		LCDLOGE("ERR: __lcd_open: lcd_init fail\r\n");
		goto error;
	}
	*plcd = lcd;

	panel = find_panel(LCD_SCLK_FREQ, LCD_WORK_MODE_INTERRUPT);
	if(NULL == panel){
		LCDLOGE("ERR: __lcd_open: get_panel_info fail\r\n");
		goto error;
	}
	*ppanel = panel;

	ret = panel_init(panel, LCD_SCLK_FREQ, LCD_WORK_MODE_INTERRUPT,0);
	if(0 != ret){
		LCDLOGE("ERR: __lcd_open: panel_init fail\r\n");
		goto error;
	}

	ret = lcd_output_setting(lcd, panel);
	if(0 != ret){
		LCDLOGE("ERR: __lcd_open: lcd_output_setting fail\r\n");
		goto error;
	}
	backlight_set_brightness(DEFAULT_BRIGHTNESS);

	LCDLOGI("Info: __lcd_open ---\r\n");
	return 0;
error:
	__lcd_close(lcd, panel);
	return -1;
}

static int __compose_test(struct s_lcd_ctx *lcd, struct panel_spec *panel)
{
	struct s_layer_setting *layer = NULL;
	int ret = 0;

	uint32_t stride_p1_c1 = 0, stride_p2_c1 = 0, stride_p3_c1 = 0;
	uint32_t stride_p1_c2 = 0, stride_p2_c2 = 0, stride_p3_c2 = 0;
	uint32_t stride_p1_c3 = 0, stride_p2_c3 = 0, stride_p3_c3 = 0;
	uint32_t addr_p1_c1 = 0, addr_p1_c2 = 0, addr_p1_c3 = 0;
	uint32_t addr_p2_c1 = 0, addr_p3_c1 = 0;
	uint32_t addr_p2_c2 = 0, addr_p3_c2 = 0;
	uint32_t addr_p2_c3 = 0, addr_p3_c3 = 0;
	uint32_t plane = 1;
	uint32_t test_format_c1 = LCD_FORMAT_RGBA888;/*osd2 layer*/
	uint32_t test_format_c2 = LCD_FORMAT_RGB888A;/*osd1 layer*/
	uint32_t test_format_c3 = LCD_FORMAT_RGB888A; /*img layer*/
	uint32_t test_width = 240;
	uint32_t test_height = 320;
	uint32_t size_c1, size_c2, size_c3;

	LCDLOGI("Info: ComposeTest +++\r\n");
	LCDLOGI("Info: ComposeTest: Test compose capability\r\n");

	if((NULL == lcd) || (NULL == panel)){
		LCDLOGE("Err: ComposeTest: Invalid param!\r\n");
		return -1;
	}

	test_width = panel->width;
	test_height = panel->height;

	size_c1 = test_width * test_height * get_format_bpp(test_format_c1) / 8;
	size_c2 = test_width * test_height * get_format_bpp(test_format_c2) / 8;
	size_c3 = test_width * test_height * get_format_bpp(test_format_c3) / 8;

	addr_p1_c1 = (uint32_t)malloc(size_c1);
	if(NULL == addr_p1_c1){
		LCDLOGE("Err: ComposeTest: Can't allocate buffer!\r\n");
		ret = -1;
		goto exit1;
	}
	addr_p1_c2 = (uint32_t)malloc(size_c2);
	if(NULL == addr_p1_c2){
		LCDLOGE("Err: ComposeTest: Can't allocate buffer!\r\n");
		ret = -1;
		goto exit1;
	}
	addr_p1_c3 = (uint32_t)malloc(size_c3);
	if(NULL == addr_p1_c3){
		LCDLOGE("Err: ComposeTest: Can't allocate buffer!\r\n");
		ret = -1;
		goto exit1;
	}

	LCDLOGI("INFO: before lcd_draw_images\r\n");
	//osd2 layer
	lcd_draw_images(addr_p1_c1,&addr_p2_c1,&addr_p3_c1,test_format_c1,
		IMG_PATTERN_VCB_5,test_width,test_height,&stride_p1_c1,&stride_p2_c1,&stride_p3_c1);
	//osd1 layer
	lcd_draw_images(addr_p1_c2,&addr_p2_c2,&addr_p3_c2,test_format_c2,
		IMG_PATTERN_HCB_5,test_width,test_height,&stride_p1_c2,&stride_p2_c2,&stride_p3_c2);
	//img layer
	lcd_draw_images(addr_p1_c3,&addr_p2_c3,&addr_p3_c3,test_format_c3,
		IMG_PATTERN_VCB_2,test_width,test_height,&stride_p1_c3,&stride_p2_c3,&stride_p3_c3);
	LCDLOGI("INFO: after lcd_draw_images\r\n");
	size_c1 = ROUND_UP(size_c1,32);
	CacheCleanMemory((void*)addr_p1_c1, size_c1);
	size_c2 = ROUND_UP(size_c2,32);
	CacheCleanMemory((void*)addr_p1_c2, size_c2);
	size_c3 = ROUND_UP(size_c3,32);
	CacheCleanMemory((void*)addr_p1_c3, size_c3);

	lcd->bg_color = 0xFF;
	lcd->alpha_mode = LCD_ALPHA_MODE_NORMAL;
	lcd->gamma_en = 0;
	lcd->wb_setting.wb_en = 0;
	lcd->dither_setting.dither_en = 0;

	layer = &lcd->layer_setting[LCD_LAYER_IMG];
	layer->format = test_format_c3;
	layer->alpha_sel = LCD_ALPHA_LAYER;
	layer->layer_alpha = 0xFF;
	layer->mirror_en = 0;
	layer->src_buffer[0].addr = addr_p1_c3;
	layer->src_buffer[0].width = test_width;//panel->width;
	layer->src_buffer[0].height = test_height;
	layer->src_buffer[0].stride = stride_p1_c3;
	plane = get_format_plane(test_format_c3);
	if(plane == 3){
		layer->src_buffer[2].addr = addr_p3_c3;
		layer->src_buffer[2].width = test_width;
		layer->src_buffer[2].height = test_height;
		layer->src_buffer[2].stride = stride_p3_c3;
	}
	if(plane != 1){
		layer->src_buffer[1].addr = addr_p2_c3;
		layer->src_buffer[1].width = test_width;
		layer->src_buffer[1].height = test_height;
		layer->src_buffer[1].stride = stride_p2_c3;
	}
	layer->dest_point.x = 0;
	layer->dest_point.y = 0;
	layer->ck_setting.ck_en = 0;
	layer->cbsh_setting.cbsh_en = 0;

	layer = &lcd->layer_setting[LCD_LAYER_OSD1];
	layer->format = test_format_c2;
	layer->alpha_sel = LCD_ALPHA_LAYER;
	layer->layer_alpha = 0x80;
	layer->mirror_en = 0;
	layer->src_buffer[0].addr = addr_p1_c2;
	layer->src_buffer[0].width = test_width;
	layer->src_buffer[0].height = test_height;
	layer->src_buffer[0].stride = stride_p1_c2;
	plane = get_format_plane(test_format_c2);
	if(plane == 3){
		layer->src_buffer[2].addr = addr_p3_c2;
		layer->src_buffer[2].width = test_width;
		layer->src_buffer[2].height = test_height;
		layer->src_buffer[2].stride = stride_p3_c2;
	}
	if(plane != 1){
		layer->src_buffer[1].addr = addr_p2_c2;
		layer->src_buffer[1].width = test_width;
		layer->src_buffer[1].height = test_height;
		layer->src_buffer[1].stride = stride_p2_c2;
	}
	layer->dest_point.x = 0;
	layer->dest_point.y = 0;
	layer->ck_setting.ck_en = 0;
	layer->cbsh_setting.cbsh_en = 0;

	layer = &lcd->layer_setting[LCD_LAYER_OSD2];
	layer->format = test_format_c1;
	layer->alpha_sel = LCD_ALPHA_LAYER;
	layer->layer_alpha = 0x80;
	layer->mirror_en = 0;
	layer->src_buffer[0].addr = addr_p1_c1;
	layer->src_buffer[0].width = test_width;
	layer->src_buffer[0].height = test_height;
	layer->src_buffer[0].stride = stride_p1_c1;
	plane = get_format_plane(test_format_c1);
	if(plane == 3){
		layer->src_buffer[2].addr = addr_p3_c1;
		layer->src_buffer[2].width = test_width;
		layer->src_buffer[2].height = test_height;
		layer->src_buffer[2].stride = stride_p3_c1;
	}
	if(plane != 1){
		layer->src_buffer[1].addr = addr_p2_c1;
		layer->src_buffer[1].width = test_width;
		layer->src_buffer[1].height = test_height;
		layer->src_buffer[1].stride = stride_p2_c1;
	}
	layer->dest_point.x = 0;
	layer->dest_point.y = 0;
	layer->ck_setting.ck_en = 0;
	layer->cbsh_setting.cbsh_en = 0;

	lcd_enable_layer(lcd, LCD_LAYER_IMG);
	lcd_enable_layer(lcd, LCD_LAYER_OSD1);
	lcd_enable_layer(lcd, LCD_LAYER_OSD2);

	LCDLOGI("INFO: refresh frame!\r\n");
	ret = panel_before_refresh(panel, 0, 0, panel->height, panel->width);
	if(0 != ret){
		LCDLOGE("ERROR: panel_before_refresh fail\r\n ");
		ret = -1;
		goto exit1;
	}
	ret = lcd_refresh(lcd);
	if(0 != ret){
		LCDLOGE("ERROR: lcd_refresh fail\r\n ");
		ret = -1;
		goto exit1;
	}
	ret = lcd_after_refresh(lcd);
	if(0 != ret){
		LCDLOGE("ERROR: lcd_after_refresh fail\r\n ");
		ret = -1;
		goto exit1;
	}

	ret = panel_after_refresh(panel);
	if(0 != ret){
		LCDLOGE("ERROR: panel_after_refresh fail\r\n ");
		ret = -1;
		goto exit1;
	}

exit1:
	free((void*)addr_p1_c1);
	free((void*)addr_p1_c2);
	free((void*)addr_p1_c3);
	LCDLOGI("Info: ComposeTest ---\r\n");
	return ret;
}

